"""Generate configs/collab/collab.yaml from the recorded runs of the real ogbl-collab rows (never edit the YAML by hand).

    python scripts/make_collab_config.py --ref <root of the original experiment tree>

Contents
  gcn        the GCN (ERM) training argv of the FLEX backbone (10 seeds, --seed s) and the hyper-parameters parsed from it
  iss        the ISS training config shared by the 20 shipped ISS models (from their cfg.json; seed / fit_max vary)
  baselines  per GCN+age10 baseline method, the recorded 10-seed training argv (method-specific flags included)
  backbones  NCN, RGAE (Refined-GAE) and gMPNN_ref: the recorded final argv and the model hyper-parameters read from the
             argparse Namespace each final printed (seed 1; every seed's Namespace is asserted equal up to the seed)
"""
import argparse
import json
import re
import shlex
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
GCN_SCRIPT = 'logs_rstar/train_erm_seeds.sh'
ISS_DIR = REPO / 'review_weights/ogbl-collab/iss'
HARNESS_MANIFEST = 'ood_final_rstar/_manifest.jsonl'
BASELINES = ('ERM', 'IRM', 'VRex', 'GroupDRO', 'CORAL', 'DANN', 'SRGNN', 'VGAE')
HP = {'hidden_channels': int, 'num_layers': int, 'num_layers_predictor': int, 'dropout': float, 'edge_drop': float,
      'lr': float, 'l2': float, 'batch_size': int, 'epochs': int, 'kill_cnt': int}
DROP = ('--device', '--checkpoint_dir', '--fidelity_csv', '--gpu_mem_cap_gb', '--save', '--seed', '--runs')


def clean_argv(argv):
    """Training argv without the interpreter / script, machine-specific flags, seed and run count."""
    argv = argv[argv.index('gnn_baseline.py') + 1:]
    out, i = [], 0
    while i < len(argv):
        k = argv[i]
        has_val = i + 1 < len(argv) and not argv[i + 1].startswith('--')
        if k not in DROP:
            out += [k, argv[i + 1]] if has_val else [k]
        i += 2 if has_val else 1
    return out


def hp_of(argv):
    return {k: cast(argv[argv.index(f'--{k}') + 1]) for k, cast in HP.items()}


def backbone_entry(ref, method):
    sys.path.insert(0, str(REPO / 'scripts'))
    from make_baseline_configs import HP, namespace
    d = ref / 'ood_final_backbone' / method / 'ogbl-collab'
    if method == 'gMPNN_ref':
        ns = namespace(d / 'final.txt')
        hp = {'dropout': float(ns['dropout']), 'gmpnn_hidden_channels': int(ns['gmpnn_hidden_channels']),
              'gmpnn_predictor_layers': int(ns['gmpnn_predictor_layers'])}
        return {'argv': clean_argv(['gnn_baseline.py'] + shlex.split((d / 'cmd.txt').read_text())), 'hp': hp}
    nss = [namespace(d / f'seed{s}.txt') for s in range(1, 11)]
    strip = lambda n: {k: v for k, v in n.items() if k not in ('seed', 'checkpoint_dir')}  # noqa: E731
    assert all(strip(n) == strip(nss[0]) for n in nss), method
    ns = nss[0]
    hp = {k: (int(ns[k]) if k in ('hidden_channels', 'num_layers', 'num_layers_predictor') else float(ns[k])) for k in HP}
    hp.update({k: v for k, v in ns.items() if k.startswith('ncn_' if method == 'NCN' else 'rgae_')})
    return {'hp': hp, 'batch_size': int(ns['batch_size']), 'train_year_min': int(ns.get('train_year_min', 0))}   # absent from older Namespaces = 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ref', required=True)
    a = ap.parse_args()
    ref = Path(a.ref)
    line = next(ln for ln in (ref / GCN_SCRIPT).read_text().splitlines() if 'gnn_baseline.py' in ln and 'CMD=' in ln)
    gcn = clean_argv(shlex.split(re.sub(r'\$\w+', 'X', line.split('CMD="', 1)[1].rsplit('"', 1)[0])))
    cfgs = [json.loads((d / 'cfg.json').read_text()) for d in sorted(ISS_DIR.iterdir())]
    shared = {k: v for k, v in cfgs[0].items() if k not in ('seed', 'fit_max', 'hash', 'tag')}
    assert all({k: v for k, v in c.items() if k not in ('seed', 'fit_max', 'hash', 'tag')} == shared for c in cfgs)
    recs = [json.loads(ln) for ln in open(ref / HARNESS_MANIFEST)]
    base = {}
    for m in BASELINES:
        r = [x for x in recs if x.get('method') == m and x.get('cell') == 'ogbl-collab_rstar' and x.get('status') == 'ok' and x.get('cmd')][-1]
        base[m] = {'argv': clean_argv(r['cmd']), 'seeds': list(range(1, 11))}
    out = {'gcn': {'argv': gcn, 'seeds': list(range(1, 11)), 'hp': hp_of(gcn)},
           'iss': {'shared': shared, 'seeds': list(range(1, 11)), 'fit_max': [2017, 2018]},
           'baselines': base, 'backbones': {m: backbone_entry(ref, m) for m in ('NCN', 'RGAE', 'gMPNN_ref')}}
    p = REPO / 'configs/collab/collab.yaml'
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text('# generated by scripts/make_collab_config.py from the recorded runs; do not edit\n' + yaml.safe_dump(out, sort_keys=False))
    print(p)


if __name__ == '__main__':
    main()
