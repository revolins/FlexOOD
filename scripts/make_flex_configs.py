"""Generate configs/flex/<cell>.yaml from the headline manifest of the original runs (never edit the YAML by hand).

    python scripts/make_flex_configs.py --ref <reference tree> [--manifest logs_flexport/release/headline_manifest.json]

Per cell: the selected variant, the exact recorded training argv, the RunSpec fields parsed from it, the recorded picks
(weights mode asserts them), the paper's mean / std and, for _AD rows, the validation-only AA-DC calibration.
"""
import argparse
import json
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
INT = ('num_layers', 'num_layers_predictor', 'hidden_channels', 'epochs', 'eval_steps', 'kill_cnt', 'runs', 'seed',
       'batch_size', 'val_batch_size', 'test_batch_size')
FLOAT = ('lr', 'dropout', 'l2', 'edge_drop')
IGNORED = ('--device', '--log_steps', '--score_model', '--use_rand', '--dblp_full_batch')
HP = ('hidden_channels', 'num_layers', 'num_layers_predictor', 'dropout', 'edge_drop', 'lr', 'l2')


def parse_argv(argv):
    out, i = {}, 0
    while i < len(argv):
        k = argv[i]
        assert k.startswith('--'), argv
        flag = i + 1 == len(argv) or argv[i + 1].startswith('--')
        out[k[2:]] = True if flag else argv[i + 1]
        i += 1 if flag else 2
    return out


def train_section(argv):
    a = parse_argv(argv)
    assert a.get('gnn_model', 'GCN') == 'GCN' and a.get('score_model', 'mlp_score') == 'mlp_score'
    if a['dataset'] == 'dblp':
        assert a.get('dblp_full_batch'), 'only the full-batch DBLP trainer is ported'
    known = set(INT) | set(FLOAT) | {'dataset', 'gnn_model', 'x_d', 'val_edges_test_input'} | {k[2:] for k in IGNORED}
    assert set(a) <= known, set(a) - known
    t = {k: int(a[k]) for k in INT if k in a and k not in HP}
    t['hp'] = {k: (int(a[k]) if k in INT else float(a[k])) for k in HP}
    t['backbone'] = 'GCN'
    t['val_edges_test_input'] = a.get('val_edges_test_input', '0') == '1'
    t['x_d'] = bool(a.get('x_d', False))
    return t


def rel_ckpt(p):
    """Checkpoint directory of the original run relative to the reference tree (None: that run did not save weights)."""
    return p[p.index('/output/') + 1:] if p else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ref', required=True)
    ap.add_argument('--manifest', default='logs_flexport/release/headline_manifest.json')
    ap.add_argument('--out', default=str(REPO / 'configs/flex'))
    a = ap.parse_args()
    ref = Path(a.ref)
    man = json.loads((ref / a.manifest).read_text())
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for cell, e in man.items():
        if 'argv' not in e:              # the real ogbl-collab row has its own pipeline (flex_www.collab)
            continue
        src = Path(e['source'])
        rel = src.as_posix()[src.as_posix().index('/output/') + 1:]
        run_json = json.loads((ref / rel).read_text())
        cfg = {'cell': cell, 'variant': e['variant'], 'metric': e['metric'], 'argv': e['argv'], 'train': train_section(e['argv']),
               'expected': {'g': [float(x) for x in e['picks']], 'b': e.get('b')},
               'paper': {'test_mean': e['test_mean'], 'test_std': e['test_std']},
               'reference': {'run_json': rel, 'caps': (str(Path(rel).parent / f'caps_{src.stem}.npz') if e.get('has_caps') else None),
                             'checkpoint_dir': rel_ckpt(run_json.get('checkpoint_dir'))}}
        assert run_json['picks']['g'] == cfg['expected']['g'], cell
        if e.get('aadc'):
            c = json.loads((ref / 'output/aadc' / f'{cell}.json').read_text())
            cfg['aadc_calibration'] = {'gate_thresholds': c['gate_thresholds'], 'anchor_scale': c['anchor_scale']}
        (out / f'{cell}.yaml').write_text('# generated by scripts/make_flex_configs.py from the headline manifest\n'
                                          + yaml.safe_dump(cfg, sort_keys=False, default_flow_style=None, width=120))
        print('wrote', out / f'{cell}.yaml')


if __name__ == '__main__':
    main()
